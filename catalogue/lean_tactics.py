"""Proofs of generated catalogue entries by a fixed list of tactics.

The statements of every accepted entry are in
``lean/Nary/Catalogue/Statements.lean`` (``catalogue.lean``). Hand-written
entries are proved by hand in ``lean/Nary/Catalogue.lean``; entries
generated from SymPy's tests (``catalogue.from_tests``) are never proved by
hand. Instead ``python -m catalogue.lean_tactics`` tries the tactics of
``TACTICS``, in order, on each generated accepted entry, and writes
``lean/Nary/Catalogue/Tactics.lean`` with a theorem for each entry that one
of them proves, using the first that does. The others are stated only.

Running it needs Lean (it runs ``lake env lean`` once per tactic on a
temporary file next to the project, after ``lake build
Nary.Catalogue.Statements``), so the Python tests do not run it; they check
that the file is what ``render`` writes from the proofs it records (every
proof is one of ``TACTICS``, for a generated accepted entry), and ``lake
build --wfail`` checks that every proof in it is accepted by Lean.
"""

import re
import subprocess
import tempfile
from pathlib import Path

from .entries import with_status
from .lean import TACTIC_PROOFS, _LEAN

__all__ = ["PATH", "TACTICS", "attempt", "proofs", "render", "write"]

PATH = TACTIC_PROOFS

# The definitions of Nary's meanings, unfolded by every tactic.
_UNFOLD = ("Nary.Add, Nary.Mul, Nary.Pow, Nary.withDomain₂, Nary.withDomain, Nary.powDomain, "
           "Nary.powTotal, Nary.lit, Nary.exp, Nary.log, Nary.logDomain, Nary.sin, Nary.cos, "
           "Nary.tan, Nary.tanDomain, Nary.re, Nary.I, Nary.pi, Nary.E, Nary.Holds, Nary.Eq, "
           "Nary.Ne, Nary.Lt, Nary.Le, Nary.Gt, Nary.Ge, Nary.And, Nary.Or, Nary.Not")

# The same without Pow's own definitions, for the tactics that use
# pow_some_eq_cpow (lean/Nary/Catalogue/TacticLemmas.lean) instead.
_UNFOLD_CPOW = _UNFOLD.replace("Nary.Pow, Nary.withDomain₂, ", "").replace("Nary.powTotal, ", "")

# The fixed list of tactics, tried in this order: (label, tactic). Each runs
# after the statement is unfolded and its binders and condition introduced.
TACTICS = (
    ("simp", f"simp [{_UNFOLD}]"),
    ("simp-norm_num", f"simp [{_UNFOLD}] <;> norm_num"),
    ("simp-ring_nf", f"simp [{_UNFOLD}] <;> ring_nf"),
    ("simp-exp_add", f"simp [{_UNFOLD}, ← Complex.exp_add] <;> ring_nf"),
    ("simp-exp_log", f"simp [{_UNFOLD}, Complex.exp_neg, Complex.exp_log, ← Complex.exp_add] "
                     f"<;> ring_nf"),
    ("simp-split", f"simp [{_UNFOLD}] <;> split_ifs <;> simp_all <;> ring_nf"),
    ("norm_num-ext", f"norm_num [{_UNFOLD}, Complex.ext_iff]"),
    # Pow as Mathlib's cpow (TacticLemmas.lean), then cpow of literals.
    ("cpow", f"simp [{_UNFOLD_CPOW}, pow_some_eq_cpow, Complex.cpow_neg, Complex.cpow_ofNat] "
             f"<;> norm_num"),
)

HEADER = """\
/-
GENERATED by `python -m catalogue.lean_tactics`. Do not edit: it is
written by trying the fixed tactics of `catalogue/lean_tactics.py`
(TACTICS) on each catalogue entry generated from SymPy's tests
(`catalogue/from_tests`), in order, and keeping the first that proves it.
Entries no tactic proves are stated in `Statements.lean` and not proved.
-/
import Nary.Catalogue.Statements
import Nary.Catalogue.TacticLemmas
import Mathlib.Analysis.SpecialFunctions.Trigonometric.Deriv

-- The tactics are fixed and shared by all entries, so some of their parts
-- do nothing on a given entry; `lake build --wfail` would fail on the
-- linters' warnings about that.
set_option linter.unusedSimpArgs false
set_option linter.unnecessarySeqFocus false
set_option linter.unusedTactic false
set_option linter.unreachableTactic false
"""

_PREAMBLE = [line for line in HEADER.splitlines()
             if line.startswith(("import ", "set_option "))]


def _theorem(name, label):
    tactic = dict(TACTICS)[label]
    return (f"-- tactic: {label}\n"
            f"theorem {name} : Statement.{name} := by\n"
            f"  unfold Statement.{name}\n"
            f"  intros\n"
            f"  {tactic}")


def render(proved):
    """The text of ``Tactics.lean`` for ``proved``, a dict from entry name to
    the label of the tactic that proves it, in the order of the entries."""
    order = [e.name for e in candidates()]
    body = "\n\n".join(_theorem(name, proved[name]) for name in order if name in proved)
    return (f"{HEADER}\nnamespace Nary.Catalogue\n\n{body}\n\nend Nary.Catalogue\n"
            if body else f"{HEADER}\nnamespace Nary.Catalogue\nend Nary.Catalogue\n")


def candidates():
    """The entries the tactics are tried on: the generated accepted ones."""
    return [e for e in with_status("accepted") if e.generated]


def proofs(text=None):
    """``{name: tactic label}`` recorded in ``Tactics.lean``."""
    text = PATH.read_text(encoding="utf-8") if text is None else text
    return {m.group(2): m.group(1) for m in re.finditer(
        r"^-- tactic: (\S+)\ntheorem (\w+) : Statement\.\2 ", text, re.M)}


def _failures(output, starts):
    """The names whose theorem has an error or a warning (``lake build
    --wfail`` fails on both), from Lean's messages
    ``<file>:<line>:<col>: error`` and the first line of each theorem."""
    failed = set()
    for m in re.finditer(r"^[^\n]*?:(\d+):\d+: (?:error|warning)", output, re.M):
        line = int(m.group(1))
        owner = max((s for s in starts if s[0] <= line), default=None)
        if owner is None:
            raise RuntimeError(f"an error outside the theorems:\n{output[:2000]}")
        failed.add(owner[1])
    return failed


def attempt(names, label, timeout=1800):
    """The subset of ``names`` that the tactic ``label`` proves."""
    lines = _PREAMBLE + ["", "namespace Nary.Catalogue", ""]
    starts = []
    for name in names:
        starts.append((len(lines) + 1, name))
        lines += _theorem(name, label).splitlines() + [""]
    lines.append("end Nary.Catalogue")
    with tempfile.NamedTemporaryFile("w", suffix=".lean", dir=_LEAN, delete=False,
                                     encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
        path = Path(f.name)
    try:
        run = subprocess.run(["lake", "env", "lean", path.name], cwd=_LEAN, text=True,
                             capture_output=True, timeout=timeout)
    finally:
        path.unlink()
    output = run.stdout + run.stderr
    failed = _failures(output, starts)
    if run.returncode != 0 and not failed:
        raise RuntimeError(f"lean failed without an error in a theorem:\n{output[:2000]}")
    return [n for n in names if n not in failed]


def write():
    subprocess.run(["lake", "build", "Nary.Catalogue.Statements", "Nary.Catalogue.TacticLemmas"],
                   cwd=_LEAN, check=True)
    remaining = [e.name for e in candidates()]
    proved = {}
    for label, _ in TACTICS:
        if not remaining:
            break
        done = attempt(remaining, label)
        print(f"{label}: {len(done)} of {len(remaining)}")
        proved.update((name, label) for name in done)
        remaining = [n for n in remaining if n not in proved]
    PATH.write_text(render(proved), encoding="utf-8")
    print(f"wrote {PATH}: {len(proved)} proved, {len(remaining)} stated only")


if __name__ == "__main__":
    write()
