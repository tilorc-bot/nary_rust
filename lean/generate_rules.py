"""Write the Lean statements of the identities and of the rules they give.

Writes ``lean/Nary/ArithmeticRules/Statements.lean`` from the identities
listed for the functions in ``FUNCTIONS`` (``nary.identities``): one Lean
declaration for each listed identity (printed with
``nary.lean.to_lean_identity``), and one for each rule that the engine
applies for an instance of a generic identity
(``nary.rules.identity_rules``), named ``<identity>_rule``, since that rule
is a consequence of the identity rather than the identity itself; and a
structure ``Proved`` with one field for each of them. The proofs are written by hand
in ``lean/Nary/ArithmeticRules.lean``, which proves ``Proved``.

Run it after changing a rule, with the Python that has ``nary`` installed:

    .venv/bin/python lean/generate_rules.py

``tests/test_lean.py`` fails while the file written here is not what this
script would write now.
"""

from pathlib import Path

from nary import Add, Mul, Pow, exp, sin
from nary.identities import identities
from nary.lean import to_lean_identity, to_lean_rule
from nary.logic import And, Or
from nary.rules import Rule, identity_rules

# The functions whose identities are stated, in this order.
FUNCTIONS = (Add, Mul, Pow, exp, sin, And, Or)

PATH = Path(__file__).resolve().parent / "Nary" / "ArithmeticRules" / "Statements.lean"

HEADER = """\
/-
GENERATED by lean/generate_rules.py from the identities listed in
python/nary (nary.identities). Do not edit: change the identities in Python
and run

    .venv/bin/python lean/generate_rules.py

The statement of each identity listed for Add, Mul, Pow, exp, sin, And and Or,
named <function>_<identity>, and of each rule the engine applies for an
instance of a generic identity, named <function>_<identity>_rule. A generic
identity is its definition in `Nary/Facts.lean` applied to the function and
the parameters. A specific identity, and a rule, says: for all values of
its variables, where its condition holds and its erased variables have a
value, the left side equals the right side. The proofs are in
`Nary/ArithmeticRules.lean`, which must prove the structure `Proved` below.
-/
import Nary.Calculus
import Nary.Facts
import Nary.Logic
"""


def render():
    """The text of the generated Lean file."""
    declarations = []
    for f in FUNCTIONS:
        block = identities(f)
        for i in block:
            when = f" when `{i.when!r}`" if i.generic is not None and i.when is not None else ""
            declarations.append(f"/-- `{i.item!r}`{when} listed for `{f!r}` -/\n{to_lean_identity(i)}")
        derived = {i.name for i in block if i.generic is not None}
        for r in identity_rules(f):
            if r.name in derived:
                renamed = Rule(r.pattern, r.replacement, when=r.condition, name=f"{r.name}_rule")
                declarations.append(f"/-- `{r!r}` -/\n{to_lean_rule(renamed)}")
    names = [d.split("abbrev ", 1)[1].split()[0] for d in declarations]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise ValueError(f"two statements have the same name: {', '.join(duplicates)}")
    fields = "".join(f"\n  {name} : Statement.{name}" for name in names)
    return (
        f"{HEADER}\nnamespace Nary.ArithmeticRules.Statement\n\n"
        + "\n\n".join(declarations)
        + "\n\nend Nary.ArithmeticRules.Statement\n\nnamespace Nary.ArithmeticRules\n\n"
        "/-- Every statement above. `Nary/ArithmeticRules.lean` proves it, so `lake build`\n"
        "fails if a statement has no proof there or a proof no longer fits. -/\n"
        f"structure Proved : Prop where{fields}\n\nend Nary.ArithmeticRules\n"
    )


if __name__ == "__main__":
    PATH.parent.mkdir(exist_ok=True)
    PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {PATH}")
